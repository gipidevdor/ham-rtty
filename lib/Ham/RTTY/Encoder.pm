package Ham::RTTY::Encoder;
use 5.020;
use strict;
use warnings;
use Ham::RTTY::_Internal::Symbols  qw(alphabet prosigns);
use Ham::RTTY::_Internal::Validate qw(fail number options named_arguments);
our $VERSION = '0.001';

sub new {
    my ($class, @pairs) = @_;
    my $self = bless $class->validate(@pairs), $class;
    return $self;
}

sub validate {
    my ($class, @pairs) = @_;
    my %args = named_arguments(@pairs);
    my $args = \%args;
    options($args, qw(wpm effective_wpm unknown));
    my $wpm       = number('wpm',           $args->{wpm}           // 20,   1, 200);
    my $effective = number('effective_wpm', $args->{effective_wpm} // $wpm, 1, $wpm);
    my $unknown   = $args->{unknown} // 'error';
    fail('RTTY_E_ARGUMENT', 'unknown must be error or skip') unless $unknown =~ /\A(?:error|skip)\z/x;
    return {wpm => $wpm, effective_wpm => $effective, unknown => $unknown};
}

sub encode {
    my ($self, $text) = @_;
    fail('RTTY_E_ARGUMENT', 'Text must be a defined scalar') if !defined($text) || ref($text);
    if ($self->{unknown} eq 'error' && $text =~ /([^\S\x00-\x7f])/x) {
        _unsupported($1, $-[1] + 1);
    }
    my $a = alphabet();
    my $p = prosigns();
    my @words;
    while ($text =~ /([^\x20\t\r\n\f\x0b]+)/gx) {
        my $word        = $1;
        my $start       = $-[1];
        my $word_length = length $word;
        my @codes;
        while (length $word) {
            my ($token, $code);
            my $position = $start + $word_length - length($word) + 1;
            if ($word =~ s/\A<([A-Za-z]+)>//x) {
                $token = "<$1>";
                $code  = $p->{uc $1};
            }
            else {
                $token = substr($word, 0, 1, '');

                # Uppercase only the explicitly supported alphabet; no transliteration.
                my $upper = $token =~ /[a-z\x{e9}]/x ? uc($token) : $token;
                $code = $a->{$upper};
            }
            if (!defined $code) {
                next if $self->{unknown} eq 'skip';
                _unsupported($token, $position);
            }
            push @codes, $code;
        }
        push @words, join(' ', @codes) if @codes;
    }
    return join(' / ', @words);
}

sub _unsupported {
    my ($symbol, $position) = @_;
    my $label = length($symbol) == 1 ? sprintf('U+%04X', ord $symbol) : $symbol;
    $label = qq{'$symbol' ($label)} if $symbol =~ /\A[\x21-\x7e]\z/x;
    return Ham::RTTY::Error->throw(
        code    => 'RTTY_E_SYMBOL',
        message => "Unsupported text symbol $label at character $position; "
            . "use supported Morse characters or unknown => 'skip'",
        context => {symbol => $symbol, position => $position}
    );
}

sub events {
    my ($self, $text) = @_;
    my $morse = $self->encode($text);
    my $dot   = 1_200_000 / $self->{wpm};
    my $space = (60_000_000 / $self->{effective_wpm} - 31 * $dot) / 19;
    my (@segments, $time, $boundary);
    $time = $boundary = 0;
    my $append = sub {
        my ($state, $duration) = @_;
        $time += $duration;
        my $end = int($time + 0.5);
        push @segments, {state => $state, duration => $end - $boundary};
        $boundary = $end;
    };
    my @words = split m{\x20/\x20}x, $morse;
    for my $wi (0 .. $#words) {
        $append->('off', 7 * $space) if $wi;
        my @letters = split /\x20/x, $words[$wi];
        for my $li (0 .. $#letters) {
            $append->('off', 3 * $space) if $li;
            my @marks = split //, $letters[$li];
            for my $mi (0 .. $#marks) {
                $append->('off', $dot) if $mi;
                $append->('on',  ($marks[$mi] eq '.' ? 1 : 3) * $dot);
            }
        }
    }
    return {unit => 'us', segments => \@segments};
}
1;

=encoding UTF-8

=head1 NAME

Ham::RTTY::Encoder - encode Morse notation and timed keying events

=head1 SYNOPSIS

    use strict;
    use warnings;
    use Ham::RTTY::Encoder;

    my $encoder = Ham::RTTY::Encoder->new(wpm => 20, effective_wpm => 12);
    my $morse = $encoder->encode('CQ <AR>');
    my $events = $encoder->events('CQ TEST');
    print "$morse\n";

=head1 DESCRIPTION

Converts a Perl character string into dot/dash notation or alternating keyed
ON/OFF durations. No audio is generated by this class. Use
L<Ham::RTTY::Generator> for event-to-sample synthesis or L<Ham::RTTY/write_wav>
for text-to-file output.

=head1 METHODS

=head2 new

    my $encoder = Ham::RTTY::Encoder->new(%options);

Returns a new encoder. Named options:

=over 4

=item * C<wpm>: 20 by default; finite number 1..200, including fractional speeds.

=item * C<effective_wpm>: defaults to WPM; finite number 1..WPM.

=item * C<unknown>: C<error> by default, or C<skip>.

=back

Undefined optional values use defaults. Invalid, duplicate and unknown
options raise C<RTTY_E_ARGUMENT>.

=head2 validate

    my $configuration = Ham::RTTY::Encoder->validate(%options);

Validates the same options as C<new> and returns a fresh normalized
configuration hash without constructing an instance. Unknown names, duplicate
options and invalid values raise the same errors as C<new>. Defaults are
resolved in the returned hash; effective WPM is an explicit numeric value there.
Keep the original option list when later per-call overrides should retain
omitted-default semantics.

=head2 encode

    my $morse = $encoder->encode($text);

Returns a string with one space between characters and C< / > between words.
Leading/trailing ASCII whitespace is ignored; space, tab, CR, LF, form feed
and vertical tab separate words. Empty input returns an empty string.
Undefined input or a reference raises C<RTTY_E_ARGUMENT>.

Unsupported characters/prosigns raise C<RTTY_E_SYMBOL>, with the original
one-based character position and symbol in the exception context. Unicode
whitespace is unsupported. C<unknown =E<gt> 'skip'> omits unsupported tokens;
if nothing supported remains, the result is empty. No transliteration occurs.

=head2 events

    my $events = $encoder->events($text);

Returns a fresh TimedEvents hash:

    { unit => 'us', segments => [
        { state => 'on',  duration => 60000 },
        { state => 'off', duration => 60000 },
        # Remaining marks and gaps follow in the same format.
    ] }

This fragment illustrates the shape; a complete event sequence is returned
by the method. Durations are positive integer microseconds. No leading or
terminal word gap is added. Empty text returns an empty C<segments> array.
Input text is validated before the result is returned.

=head1 SYMBOLS

Letters A..Z, digits 0..9 and accented E (U+00C9/U+00E9) are supported.
ASCII lowercase letters and lowercase accented E are normalized to uppercase.
Accented E must be a precomposed character; E followed by a combining accent
is not normalized automatically.
Decode external character encodings before calling the encoder; C<use utf8>
is needed for non-ASCII literals written in UTF-8 Perl source.

Supported punctuation and miscellaneous written signs are:

    . , : ? ' - / ( ) " = + @ ×

The symbol repertoire is strictly ITU-R M.1677-1 (2009), Annex 1,
Part I, sections 1.1.1 through 1.1.3. Other Morse alphabets and amateur-radio
extensions are not enabled. In particular C<!>, C<&>, C<;>, C<_> and C<$>
are rejected; C<unknown =E<gt> 'skip'> can omit them but never assigns them
an extended Morse code.

The following library tokens name operational signals from that table:

    Token  ITU signal                  Morse
    <AR>   Cross/addition               .-.-.
    <AS>   Wait                         .-...
    <BT>   Double hyphen                -...-
    <CT>   Starting signal              -.-.-
    <HH>   Error                        ........
    <SK>   End of work                  ...-.-
    <SN>   Understood                   ...-.

The token names are library mnemonics; the recommendation specifies signal
names and waveforms, rather than these angle-bracket spellings. Prosign names
are case-insensitive. The ITU invitation to transmit is ordinary C<K>,
C<-.->. C<< <KN> >> is not its substitute.
C<< <BK> >>, C<< <KN> >>, C<< <KA> >>, C<< <VE> >> and C<< <SOS> >> are
not accepted tokens in this repertoire. Ordinary C<SOS> is still three valid
letters, separated in the usual way; the uninterrupted nine-element signal
is outside this recommendation's table.

C<AR> is two letters; C<< <AR> >> is one signal. Shared waveforms cannot
recover the sender's original spelling: C<< <AR> >>/C<+>, C<< <BT> >>/C<=>
and C<×>/C<X>. Multiplication is encoded using X as specified in section 3.2;
decoding that waveform returns C<X>. This codec does not automatically expand
percentage, per-thousand or minute/second notation from the separate formatting
rules in section 3; callers must prepare those as the prescribed character
sequences. See L<Ham::RTTY::Decoder/SHARED WAVEFORMS>.

=head1 TIMING

The reference scale has 50 dot units per word. At character speed C<w>, a
dot lasts C<1200000 / w> microseconds; a dash is three dots and an
intra-character gap is one dot. At ordinary spacing, letter and word gaps
last three and seven dots respectively.

For effective speed C<e>, the spacing unit is
C<(60000000 / e - 31 * dot) / 19> microseconds. Letter and word gaps use
three and seven spacing units. This lengthens gaps without changing marks
or intra-character gaps. The 31/19 split gives a 50-unit reference word with
its terminal word gap; emitted events omit that terminal gap. Actual text
length and composition determine total audio duration.

Cumulative boundaries round to nearest integer microsecond, with halves
upward. Rounding each segment independently would introduce accumulated drift.
For sample conversion and resolution failures, see L<Ham::RTTY::Events>.

=head1 ERRORS

C<RTTY_E_ARGUMENT> reports invalid input/options. C<RTTY_E_SYMBOL> reports
unsupported text. Encoding does not change the input or retain incremental
state; split messages only at intended text/prosign boundaries.

